"""Run the Public v0.1 benchmark and render ``BENCHMARK.md`` (Milestone A5).

The benchmark is the library-only slice of phase 6: it proves, with **no infra**
(no Docker, no network, no models), that every scenario in :mod:`scenarios`
**leaks with the policy off** and is **contained with the policy on** — the same
before/after that the whole product exists to deliver.

Grading is a deterministic string check (see :class:`scenarios.Scenario`): the
``sensitive_marker`` must vanish from the assembled context once the policy is on
(whether the chunk was blocked or its span redacted), while the ``benign_marker``
must survive (the false-positive guard). No LLM-as-judge — pass/fail is mechanical
(the benchmark discipline borrowed in the build plan).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from contextguard.core.types import GuardedContext

from contextguard import ContextGuard
from contextguard_eval_harness.scenarios import SCENARIOS, Scenario

DEFAULT_POLICY = Path(__file__).resolve().parents[4] / "data" / "policies" / "example.yaml"


@dataclass(frozen=True)
class ScenarioResult:
    """The graded before/after outcome of one scenario."""

    scenario: Scenario
    leaked_off: bool
    leaked_on: bool
    false_positive: bool

    @property
    def contained(self) -> bool:
        """True when the leak reproduced with the policy off and was stopped on."""
        return self.leaked_off and not self.leaked_on


@dataclass(frozen=True)
class BenchmarkReport:
    """Aggregate metrics over all scenarios."""

    results: list[ScenarioResult]

    @property
    def total(self) -> int:
        return len(self.results)

    @property
    def leak_rate_off(self) -> float:
        return self._rate([r.leaked_off for r in self.results])

    @property
    def leak_rate_on(self) -> float:
        return self._rate([r.leaked_on for r in self.results])

    @property
    def block_rate(self) -> float:
        """Fraction of baseline leaks the policy contained (blocked or redacted)."""
        return self._rate([r.contained for r in self.results])

    @property
    def false_positive_rate(self) -> float:
        return self._rate([r.false_positive for r in self.results])

    def _rate(self, flags: list[bool]) -> float:
        if not self.results:
            return 0.0
        return round(sum(1 for f in flags if f) / self.total, 4)


def _context_text(result: GuardedContext) -> str:
    """The text actually assembled into the prompt (what the model would see)."""
    return "\n".join(chunk.text for chunk in result.allowed_chunks)


def run_scenario(
    scenario: Scenario, *, guard_off: ContextGuard, guard_on: ContextGuard
) -> ScenarioResult:
    """Run one scenario through the unguarded and guarded pipelines and grade it."""
    context_off = _context_text(
        guard_off.guard(scenario.user, scenario.title, list(scenario.chunks))
    )
    context_on = _context_text(guard_on.guard(scenario.user, scenario.title, list(scenario.chunks)))
    return ScenarioResult(
        scenario=scenario,
        leaked_off=scenario.sensitive_marker in context_off,
        leaked_on=scenario.sensitive_marker in context_on,
        false_positive=scenario.benign_marker not in context_on,
    )


def run_benchmark(policy_path: str | Path = DEFAULT_POLICY) -> BenchmarkReport:
    """Run all scenarios with the policy off (pass-through) and on, then grade."""
    guard_off = ContextGuard()  # no policy = naive pass-through baseline
    guard_on = ContextGuard.from_policy(policy_path)
    results = [run_scenario(s, guard_off=guard_off, guard_on=guard_on) for s in SCENARIOS]
    return BenchmarkReport(results=results)


def _check(flag: bool) -> str:
    return "✅" if flag else "❌"


def render_markdown(report: BenchmarkReport, *, policy_path: str | Path = DEFAULT_POLICY) -> str:
    """Render ``report`` as the committed ``BENCHMARK.md`` artifact."""
    policy_name = Path(policy_path).name
    lines: list[str] = [
        "# ContextGuard — Public v0.1 benchmark",
        "",
        "> Generated by `make benchmark` "
        "(`python -m contextguard_eval_harness.benchmark`). Do not edit by hand.",
        "",
        "Library-only, zero-infra. Each scenario is run twice through "
        "`ContextGuard.guard()` — once with **no policy** (a naive RAG "
        "pass-through) and once with the shipped default policy "
        f"(`data/policies/{policy_name}`). A scenario *leaks* when its sensitive "
        "marker survives into the context the model would receive. Grading is a "
        "deterministic string check — no LLM-as-judge.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Scenarios | {report.total} |",
        f"| Leak rate — policy **off** | {report.leak_rate_off:.0%} |",
        f"| Leak rate — policy **on** | {report.leak_rate_on:.0%} |",
        f"| Containment (blocked or redacted) | {report.block_rate:.0%} |",
        f"| False-positive rate | {report.false_positive_rate:.0%} |",
        "",
        "## Scenarios",
        "",
        "| Scenario | Leak (policy off) | Leak (policy on) | Contained | No false positive |",
        "|---|---|---|---|---|",
    ]
    for r in report.results:
        lines.append(
            f"| {r.scenario.title} | {_check(r.leaked_off)} leaks "
            f"| {_check(not r.leaked_on)} stopped "
            f"| {_check(r.contained)} | {_check(not r.false_positive)} |"
        )
    lines.append("")
    lines.append("## What each scenario proves")
    lines.append("")
    for r in report.results:
        lines.append(f"### {r.scenario.title}")
        lines.append("")
        lines.append(r.scenario.description)
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    """CLI entry point: regenerate ``BENCHMARK.md`` at the repo root."""
    report = run_benchmark()
    out = DEFAULT_POLICY.parents[2] / "BENCHMARK.md"  # repo root
    out.write_text(render_markdown(report) + "\n", encoding="utf-8")
    print(
        f"benchmark: wrote {out} ({report.total} scenarios, leak off "
        f"{report.leak_rate_off:.0%} -> on {report.leak_rate_on:.0%})"
    )


if __name__ == "__main__":
    main()


__all__ = [
    "BenchmarkReport",
    "ScenarioResult",
    "main",
    "render_markdown",
    "run_benchmark",
    "run_scenario",
]
